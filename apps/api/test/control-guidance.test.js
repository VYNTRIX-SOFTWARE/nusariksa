test('guided notes are observations, never autogenerated compliance ratings',()=>{
  const result=composeObservedNote({
    condition:'Belum ada SK penunjukan pejabat yang mengawasi fungsi TI.',
    evidence:'Dokumen organisasi belum ditemukan per tanggal uji.',
    followUp:'Minta konfirmasi Direksi dan unit personalia.',
  });
  assert.match(result,/Kondisi aktual: Belum ada SK/);
  assert.match(result,/Bukti diperiksa: Dokumen organisasi/);
  assert.match(result,/Tindak lanjut: Minta konfirmasi/);
  assert.doesNotMatch(result,/Peringkat:|Rating:|Memenuhi semua/);
  assert.throws(()=>composeObservedNote({condition:'',evidence:'Kebijakan ada',followUp:''}),TypeError);
  assert.throws(()=>composeObservedNote({condition:'Temuan nyata',evidence:'',followUp:''}),TypeError);
  assert.throws(()=>composeObservedNote({condition:'Kontrol belum ada',evidence:'Bukti ada\u0000',followUp:''}),TypeError);
  assert.throws(()=>composeObservedNote({condition:'Kondisi '.repeat(300),evidence:'Bukti ditemukan',followUp:''}),RangeError);
});
